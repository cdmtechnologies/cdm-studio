// Turns courses/*.ts into what the app and the database need:
//   src/lessons/courses.generated.ts   free lessons in full, paid lessons as titles and outlines only
//   supabase/seed/courses.sql          paid lesson content, exam questions (with answers) and the tutor's notes
// Run after changing a course: node scripts/courses.mjs   then run supabase/seed/courses.sql in the SQL editor.
import { build } from 'esbuild'
import { mkdirSync, mkdtempSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { tmpdir } from 'node:os'
import { pathToFileURL } from 'node:url'

const out = join(mkdtempSync(join(tmpdir(), 'courses-')), 'c.mjs')
await build({ entryPoints: ['courses/index.ts'], bundle: true, format: 'esm', platform: 'node', outfile: out, logLevel: 'error' })
const { COURSES } = await import(pathToFileURL(out).href)

const strip = ({ solution, ...l }) => l // model answers never ship
const tracks = []
const sql = ['-- Generated by scripts/courses.mjs: certified courses (paid lesson content, exams, tutor notes). Safe to run again.', 'begin;']
const q = (v) => `$cdm$${v}$cdm$`
for (const c of COURSES) {
  if (c.exam.length < 15) throw new Error(`${c.id}: the exam needs at least 15 questions`)
  const ids = new Set()
  c.lessons.forEach((l, i) => {
    if (!l.id.startsWith(c.id + '-') || ids.has(l.id)) throw new Error(`bad lesson id ${l.id}`)
    ids.add(l.id)
    if (JSON.stringify(l).includes('$cdm$')) throw new Error('reserved text')
    const paid = i >= c.free
    const meta = { title: l.title, kind: l.kind, task: l.task ?? null, hint: l.hint ?? null, body: l.body.slice(0, 4000), practice: l.practice ?? null, track: c.id, track_title: c.title, paid, order: i }
    sql.push(`insert into public.lesson_meta (id, meta) values (${q(l.id)}, ${q(JSON.stringify(meta))}::jsonb) on conflict (id) do update set meta = excluded.meta, updated_at = now();`)
    if (paid) sql.push(`insert into public.lesson_content (id, track, body) values (${q(l.id)}, ${q(c.id)}, ${q(JSON.stringify(strip(l)))}::jsonb) on conflict (id) do update set body = excluded.body, track = excluded.track, updated_at = now();`)
    else sql.push(`delete from public.lesson_content where id = ${q(l.id)};`)
  })
  sql.push(`delete from public.exam_questions where track = ${q(c.id)};`)
  c.exam.forEach((e, i) => {
    if (!(e.answer >= 0 && e.answer < e.options.length)) throw new Error(`${c.id} exam ${i + 1}: bad answer`)
    sql.push(`insert into public.exam_questions (track, n, question, options, answer) values (${q(c.id)}, ${i + 1}, ${q(e.q)}, ${q(JSON.stringify(e.options))}::jsonb, ${e.answer});`)
  })
  tracks.push({
    id: c.id, title: c.title, blurb: c.blurb, colour: c.colour, emoji: c.emoji,
    course: { level: c.level, hours: c.hours, free: c.free, skills: c.skills, careers: c.careers, examQuestions: c.exam.length },
    lessons: c.lessons.map((l, i) => (i < c.free ? { ...strip(l), outline: l.outline } : { id: l.id, title: l.title, minutes: l.minutes, kind: l.kind, outline: l.outline, body: '', paid: true })),
  })
}
sql.push('commit;', `select track, count(*) as questions from public.exam_questions group by track order by track;`)
mkdirSync('supabase/seed', { recursive: true })
writeFileSync('supabase/seed/courses.sql', sql.join('\n') + '\n')
writeFileSync('src/lessons/courses.generated.ts', `// Generated by scripts/courses.mjs from courses/*.ts. Do not edit by hand.\n// Paid lessons are titles only here: their content comes from the server after they are unlocked.\nimport type { Track } from './types'\n\nexport const COURSES: Track[] = ${JSON.stringify(tracks, null, 2)}\n`)
console.log(`courses: ${tracks.length}, lessons: ${tracks.reduce((n, t) => n + t.lessons.length, 0)}`)
